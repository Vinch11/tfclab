import {describe,it,expect} from 'vitest';
import type {ParsedPlan} from '@/lib/aiPlanParser';
import type {PlanConfig} from '@/hooks/useAITrainingPlan';
import {WorkoutLibrary} from '@/lib/workoutLibrary';
import {buildStartToRunTemplatePlan} from '@/lib/startToRunTemplate';
import {computeWeekQuotaEntry} from '@/engines/plan/sessionSizingMatrix';
import {auditSportsContinuity} from './v2-sports-validation';
const config={objective:'IM',weeksAvailable:2} as PlanConfig;
const plan=():ParsedPlan=>({title:'audit',phases:[],totalWeeks:2,weeklyQuotas:{1:computeWeekQuotaEntry('IM','age_group',12,'load',false)!,2:computeWeekQuotaEntry('IM','age_group',12,'recovery',false)!},weeks:[1,2].map(weekNumber=>({weekNumber,phase:'base',theme:'audit',sessions:['swim','bike','run'].map((sport,dayIndex)=>({weekNumber,phase:'base',weekTheme:'audit',dayName:['mardi','jeudi','samedi'][dayIndex],dayIndex:dayIndex*2+1,sport,title:'presence-only test',details:'No prescription generated by this read-only audit',isRest:false,durationMin:30}))}))});
describe('read-only sport evidence',()=>{
 it('checks every Ironman week including recovery and exposes a lost discipline',()=>{
  const input=plan();input.weeks[1].sessions=input.weeks[1].sessions.filter(s=>s.sport!=='swim');
  const before=JSON.stringify(input),report=auditSportsContinuity(input,config);
  expect(report.controls.find(c=>c.id==='triathlon_discipline_continuity')!.result).toBe('fail');
  expect(JSON.stringify(report)).toContain('recovery');expect(JSON.stringify(input)).toBe(before);
 });
 it('reports incomplete calendar as failure, not successful continuity',()=>{
  const input=plan();input.weeks.pop();expect(auditSportsContinuity(input,config).completeCalendar).toBe(false);
  expect(auditSportsContinuity(input,config).controls.find(c=>c.id==='triathlon_discipline_continuity')!.result).toBe('fail');
 });
 it('does not pretend unknown quotas or brick split are quantified progression',()=>{
  const input=plan();input.weeklyQuotas=undefined;input.weeks[0].sessions[1].sport='brick';
  const report=auditSportsContinuity(input,config);
  expect(report.controls.find(c=>c.id==='triathlon_discipline_continuity')!.result).toBe('unknown');
  expect(report.controls.find(c=>c.id==='triathlon_progression_by_discipline')!.result).toBe('unknown');
  expect(JSON.stringify(report)).toContain('brickMinutesNotAllocated');
 });
 it('uses the existing declared-race adjustment without counting competition as training',()=>{
  const input=plan();input.weeks=input.weeks.slice(0,1);input.totalWeeks=1;
  const quota=input.weeklyQuotas![1];quota.quota.run={min:1,max:1};quota.quota.bike={min:0,max:0};quota.quota.swim={min:0,max:0};quota.quota.brick={min:0,max:0};
  input.weeks[0].sessions=[{...input.weeks[0].sessions[0],sport:'run',title:'COURSE : 10K',custom:true,durationMin:0}];
  const report=auditSportsContinuity(input,{objective:'IM',weeksAvailable:1,planStartDate:'2026-10-26',raceGoals:[{objective:'10K',raceDate:'2026-11-01',priority:'B'}]} as PlanConfig);
  expect(report.controls.find(c=>c.id==='triathlon_training_frequency')!.result).toBe('pass');
  expect(JSON.stringify(report)).toContain('"isRaceWeek":true');
 });
 it('does not use a brick to exempt the standalone run quota',()=>{
  const input=plan();input.weeks[0].sessions=input.weeks[0].sessions.filter(s=>s.sport!=='run');input.weeks[0].sessions[1].sport='brick';
  const report=auditSportsContinuity(input,config);
  expect(report.controls.find(c=>c.id==='triathlon_training_frequency')!.result).toBe('fail');
  expect(JSON.stringify(report.controls.find(c=>c.id==='triathlon_training_frequency')!.evidence)).toContain('"sport":"run"');
 });
 it('marks trail progression unknown even for real elevation-bearing catalogue fiches',()=>{
  const fiche=WorkoutLibrary.find(w=>w.dPlusTargetM&&w.tags?.includes('trail'))!;
  expect(fiche).toBeTruthy();const input=plan();input.weeks=input.weeks.slice(0,1);input.totalWeeks=1;
  input.weeks[0].sessions=[{...input.weeks[0].sessions[0],sport:'run',catalogId:fiche.id,title:fiche.objectif,details:fiche.structure.map(p=>p.text).join(' ')}];
  const report=auditSportsContinuity(input,{objective:'TrailMountain',weeksAvailable:1} as PlanConfig);
  expect(report.controls.find(c=>c.id==='trail_structured_elevation_provenance')!.result).toBe('pass');
  expect(report.controls.find(c=>c.id==='trail_elevation_progression')!.execution).toBe('not_implemented');
  expect(report.controls.find(c=>c.id==='trail_muscular_specificity')!.result).toBe('unknown');
 });
 it('does not treat an unconstructed trail as validated or a road template as triathlon',()=>{
  expect(auditSportsContinuity(undefined,config).controls.find(c=>c.id==='triathlon_discipline_continuity')!.result).toBe('unknown');
  expect(auditSportsContinuity(undefined,{objective:'TrailUltra',weeksAvailable:12} as PlanConfig).controls.find(c=>c.id==='trail_structured_elevation_provenance')!.result).toBe('unknown');
  expect(auditSportsContinuity(buildStartToRunTemplatePlan(),{objective:'StartToRun',weeksAvailable:12} as PlanConfig).controls.find(c=>c.id==='triathlon_discipline_continuity')!.execution).toBe('not_applicable');
 });
});
