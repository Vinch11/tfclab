import type { V2Block, V2Goal, V2NumberParameter, V2Sport, V2WorkoutTemplate } from "./engine";

const p = (min: number, max: number, step: number, value: number): V2NumberParameter =>
  ({ min, max, step, default: value });
const c = (label: string, seconds: string, target: string, sport?: V2Sport): V2Block =>
  ({ kind: "continuous", label, seconds, target, ...(sport ? { sport } : {}) });
const i = (label: string, repeats: string, workSeconds: string, recoverySeconds: string,
  target: string, recoveryTarget = "Facile", sport?: V2Sport): V2Block =>
  ({ kind: "intervals", label, repeats, workSeconds, recoverySeconds, target, recoveryTarget,
    ...(sport ? { sport } : {}) });
const sw = (label: string, repeats: string, distanceMeters: string, recoverySeconds: string,
  cssPaceFactor: number, target: string): V2Block =>
  ({ kind: "swim_crawl_intervals", label, repeats, distanceMeters, recoverySeconds, cssPaceFactor, target });
const st = (label: string, sets: string, reps: string, tempoSecondsPerRep: string,
  recoverySeconds: string, target: string): V2Block =>
  ({ kind: "strength_sets", label, sets, reps, tempoSecondsPerRep, recoverySeconds, target });

